export function getGameBySlug(slug: string): Product | undefined {
  return games.find((g) => g.slug === slug);
}

export function getPopularGames(): Product[] {
  return games.filter((g) => g.isPopular && g.isActive);
}

export function getFeaturedGames(): Product[] {
  return games.filter((g) => g.isFeatured && g.isActive);
}

export function searchGames(query: string): Product[] {
  const q = query.toLowerCase();
  return games.filter(
    (g) =>
      g.name.toLowerCase().includes(q) ||
      g.publisher?.toLowerCase().includes(q) ||
      g.subcategory?.toLowerCase().includes(q)
  );
}
